// Generates src/styles/shadcn.css — the shadcn/ui token shim (DMNC-922).
//
// shadcn/ui (classic) consumes colours as HSL-channel triplets via
// `hsl(var(--background))`. eidotter emits full hex. This script resolves each
// eidotter semantic role to a hex value PER THEME (following the var() chains
// in the generated tokens.css + theme.*.css), converts to "H S% L%" channels,
// and emits a self-contained shim that maps shadcn var names → those channels.
//
// Consumers `@import "eidotter/shadcn.css"`, delete their own palette, and their
// existing `hsl(var(--x))` usages re-theme via [data-theme] (the per-theme
// blocks below). Regenerated by `npm run build-tokens`; freshness-checked in CI.
//
// Opt-in subpath export — NOT bundled into eidotter/styles.

import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const STYLES = resolve('src/styles');
const THEMES = ['amber-mono', 'cga-amber', 'cga-mode4-p0', 'cga-mode4-p1', 'cga-mode5'];

// shadcn var name → eidotter semantic role CSS var (without the leading --).
const MAP = {
  background: 'color-semantic-background-primary',
  foreground: 'color-semantic-text-primary',
  card: 'color-semantic-background-secondary',
  'card-foreground': 'color-semantic-text-primary',
  popover: 'color-semantic-background-secondary',
  'popover-foreground': 'color-semantic-text-primary',
  primary: 'color-semantic-background-brand',
  'primary-foreground': 'color-semantic-text-on-brand',
  secondary: 'color-semantic-background-tertiary',
  'secondary-foreground': 'color-semantic-text-primary',
  muted: 'color-semantic-background-secondary',
  'muted-foreground': 'color-semantic-text-muted',
  accent: 'color-semantic-background-accent',
  'accent-foreground': 'color-semantic-text-on-brand',
  destructive: 'color-semantic-background-error',
  'destructive-foreground': 'color-semantic-text-white',
  border: 'color-semantic-border-default',
  input: 'color-semantic-border-default',
  ring: 'color-semantic-border-focus',
  // sidebar — best-effort aliases of the core roles (override per surface).
  sidebar: 'color-semantic-background-primary',
  'sidebar-foreground': 'color-semantic-text-primary',
  'sidebar-primary': 'color-semantic-background-brand',
  'sidebar-primary-foreground': 'color-semantic-text-on-brand',
  'sidebar-accent': 'color-semantic-background-secondary',
  'sidebar-accent-foreground': 'color-semantic-text-primary',
  'sidebar-border': 'color-semantic-border-default',
  'sidebar-ring': 'color-semantic-border-focus',
  // chart — amber-family ramp; replace with a real palette for data viz.
  'chart-1': 'color-semantic-background-brand',
  'chart-2': 'color-semantic-text-muted',
  'chart-3': 'color-semantic-border-focus',
  'chart-4': 'color-semantic-background-accent',
  'chart-5': 'color-semantic-text-primary',
};

// Parse `--name: value;` pairs out of the first rule block in a CSS string
// (strips trailing /** ... */ comments from values).
function parseVars(css) {
  const open = css.indexOf('{');
  const close = css.indexOf('}', open);
  // Strip /* ... */ comments from the whole block first — a trailing comment
  // after `value;` has no `;`, so it would otherwise glue onto the next
  // declaration's name and drop it.
  const body = css.slice(open + 1, close).replace(/\/\*[\s\S]*?\*\//g, '');
  const map = {};
  for (const decl of body.split(';')) {
    const i = decl.indexOf(':');
    if (i === -1) continue;
    const name = decl.slice(0, i).trim();
    if (!name.startsWith('--')) continue;
    const val = decl.slice(i + 1).trim();
    if (name && val) map[name] = val;
  }
  return map;
}

// Resolve a CSS var to a colour string (#hex or rgb/rgba) by walking var()
// chains in `ctx` (a name→value map).
function resolveColor(varName, ctx, seen = new Set()) {
  if (seen.has(varName)) return null;
  seen.add(varName);
  const val = ctx[varName];
  if (!val) return null;
  const t = val.trim();
  if (t.startsWith('#')) return t.match(/#[0-9a-fA-F]{3,6}/)[0];
  if (t.startsWith('rgb')) return t.match(/rgba?\([^)]*\)/i)?.[0] ?? null;
  const ref = t.match(/var\(\s*(--[a-z0-9-]+)\s*(?:,\s*(#[0-9a-fA-F]{3,6}))?\s*\)/i);
  if (ref) {
    const resolved = resolveColor(ref[1], ctx, seen);
    if (resolved) return resolved;
    if (ref[2]) return ref[2]; // var() fallback hex
  }
  const hex = t.match(/#[0-9a-fA-F]{6}/);
  return hex ? hex[0] : null;
}

// Convert #hex OR rgb()/rgba() → "H S% L%" channels (alpha dropped).
function toHslChannels(color) {
  let r, g, b;
  if (color.startsWith('rgb')) {
    const n = color.match(/[\d.]+/g).map(Number);
    [r, g, b] = [n[0] / 255, n[1] / 255, n[2] / 255];
  } else {
    let h = color.replace('#', '');
    if (h.length === 3) h = h.split('').map((c) => c + c).join('');
    r = parseInt(h.slice(0, 2), 16) / 255;
    g = parseInt(h.slice(2, 4), 16) / 255;
    b = parseInt(h.slice(4, 6), 16) / 255;
  }
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let s = 0, hue = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) hue = ((g - b) / d + (g < b ? 6 : 0));
    else if (max === g) hue = (b - r) / d + 2;
    else hue = (r - g) / d + 4;
    hue /= 6;
  }
  return `${Math.round(hue * 360)} ${Math.round(s * 100)}% ${Math.round(l * 100)}%`;
}

function emitBlock(selector, ctx) {
  const lines = [`${selector} {`];
  for (const [shadcnVar, role] of Object.entries(MAP)) {
    const color = resolveColor(`--${role}`, ctx);
    if (!color) {
      lines.push(`  /* --${shadcnVar}: unresolved (${role}) */`);
      continue;
    }
    lines.push(`  --${shadcnVar}: ${toHslChannels(color)};`);
  }
  lines.push('}');
  return lines.join('\n');
}

const base = parseVars(readFileSync(resolve(STYLES, 'tokens.css'), 'utf-8'));
const blocks = [
  `/* =============================================================================
 * eidotter — shadcn/ui token shim (DMNC-922). GENERATED — do not edit.
 * Run \`npm run build-tokens\` to regenerate.
 *
 * Maps shadcn/ui CSS var names to eidotter's semantic roles as HSL channels,
 * so a shadcn consumer using \`hsl(var(--background))\` consumes eidotter's
 * themeable palette. Import this AFTER eidotter/tokens.css + eidotter/styles,
 * then delete your own :root/.dark/etc. colour definitions. Re-themes via
 * [data-theme]. Opt-in — NOT part of eidotter/styles.
 *
 * sidebar-* and chart-* are best-effort amber-family aliases; override per
 * surface for real sidebar/data-viz needs.
 * ========================================================================== */`,
  emitBlock(':root', base),
];

for (const theme of THEMES) {
  const themeVars = parseVars(readFileSync(resolve(STYLES, `theme.${theme}.css`), 'utf-8'));
  const ctx = { ...base, ...themeVars }; // theme overrides base
  blocks.push(emitBlock(`[data-theme="${theme}"], .theme-${theme}`, ctx));
}

writeFileSync(resolve(STYLES, 'shadcn.css'), blocks.join('\n\n') + '\n');
console.log('[generate-shadcn-shim] wrote src/styles/shadcn.css');
