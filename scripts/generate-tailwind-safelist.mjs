// Generates two outputs from the freshly built tailwind.preset.cjs, so neither
// can drift from the token sources:
//
// 1. The marked block in src/styles/tailwind.css — `@source inline(...)` lines that
//    compile every eidotter token utility into dist/eidotter.css, whether or
//    not a component happens to use it: text-/bg-/border- for every dos-*/
//    cga-* colour, shadow-dos-*, font-dos-* (families and weight aliases) and
//    the text-dos-text-*/text-dos-display-* sizes. Consumers without Tailwind
//    rely on these classes being in the bundle. Stock Tailwind utilities
//    (text-xs … text-9xl, generic layout) stay out: dist is unlayered, so a
//    stock class it ships beats the consumer's own layered copy.
//    The lines live in tailwind.css itself: an `@source inline()` in a file
//    pulled in with `@import` never reached the Vite lib build.
//
// 2. src/utils/dosFontSizes.ts — the dos font-size keys, which cn() registers
//    with tailwind-merge as font sizes. Without that, twMerge reads
//    `text-dos-text-sm` as a text colour and drops the real colour class.
//
// Run by `npm run build-tokens` after style-dictionary; freshness-checked in CI.

import { createRequire } from 'module';
import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const require = createRequire(import.meta.url);
const presetPath = resolve('tailwind.preset.cjs');
delete require.cache[presetPath];
const theme = require(presetPath).theme.extend;

const isDos = (key) => key.startsWith('dos-') || key === 'dos';
const isToken = (key) => isDos(key) || key.startsWith('cga-');

const colorKeys = Object.keys(theme.colors).filter(isToken);
const fontSizeKeys = Object.keys(theme.fontSize).filter(isDos);
const shadowKeys = Object.keys(theme.boxShadow).filter(isDos);
const fontKeys = [...Object.keys(theme.fontFamily), ...Object.keys(theme.fontWeight)].filter(isDos);

if (colorKeys.length === 0 || fontSizeKeys.length === 0 || shadowKeys.length === 0 || fontKeys.length === 0) {
  console.error('[generate-tailwind-safelist] FAILED — preset is missing a token group; did style-dictionary run?');
  process.exit(1);
}

const groups = [
  ['colour utilities: text-, bg- and border- for every dos and cga colour', ['text', 'bg', 'border'].flatMap((p) => colorKeys.map((k) => `${p}-${k}`))],
  ['font sizes', fontSizeKeys.map((k) => `text-${k}`)],
  ['shadows', shadowKeys.map((k) => `shadow-${k}`)],
  ['font families and weight aliases', fontKeys.map((k) => `font-${k}`)],
];

const BEGIN = '/* BEGIN GENERATED SAFELIST (scripts/generate-tailwind-safelist.mjs) */';
const END = '/* END GENERATED SAFELIST */';
const block = [
  BEGIN,
  '/* Do not edit between these markers; run `npm run build-tokens`. */',
  ...groups.flatMap(([label, classes]) => [`/* ${label} */`, `@source inline("${classes.join(' ')}");`]),
  END,
].join('\n');

const twPath = resolve('src/styles/tailwind.css');
const tw = readFileSync(twPath, 'utf8');
const start = tw.indexOf(BEGIN);
const end = tw.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error('[generate-tailwind-safelist] FAILED — safelist markers missing from src/styles/tailwind.css');
  process.exit(1);
}

const ts = [
  '// GENERATED by scripts/generate-tailwind-safelist.mjs from tailwind.preset.cjs.',
  '// Do not edit; run `npm run build-tokens`.',
  '',
  '/** The eidotter font-size keys (`text-<key>` classes), registered with tailwind-merge by cn(). */',
  'export const DOS_FONT_SIZES: readonly string[] = [',
  ...fontSizeKeys.map((k) => `  '${k}',`),
  '];',
  '',
].join('\n');

writeFileSync(twPath, tw.slice(0, start) + block + tw.slice(end + END.length));
writeFileSync(resolve('src/utils/dosFontSizes.ts'), ts);
console.log(
  `[generate-tailwind-safelist] wrote the safelist in src/styles/tailwind.css (${groups.reduce((n, [, c]) => n + c.length, 0)} classes) and src/utils/dosFontSizes.ts (${fontSizeKeys.length} sizes)`
);
