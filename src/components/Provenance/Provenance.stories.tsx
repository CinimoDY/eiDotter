        'The first paragraph of any AI-drafted devjournal entry sets the frame: model output, not yet engaged with by a human. This is what generation looks like before a single edit lands.',
        'By the second paragraph the gradient has accumulated. The reader sees a wall of saturated colour and registers it as a deliberate visual state — not an accident, not a decoration.',
        'By the third, the question is whether the eye has acclimated. Wallpaper effect: when an alarm rings continuously, you stop hearing it. The shimmer-fatigue risk is what this story exists to surface.',
