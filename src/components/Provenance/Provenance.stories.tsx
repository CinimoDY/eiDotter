/**
 * NOTE: this directory ships **no React component** of its own. Provenance
 * is a pure-CSS primitive — the canonical `[data-provenance="ai-draft"]`
 * attribute and the `[data-ai-block]` wrapper — that consumers wire up by
 * setting the HTML attribute themselves. The `AIText` component in
 * `components/AIText/` is the ergonomic React shortcut over the attribute.
 *
 * The story-only directory mirrors `src/components/Tokens/`, the existing
 * pattern for documentation-only design-system surfaces.
 */
const meta = {
  title: 'Design System/Content Provenance',
  parameters: {
    layout: 'padded',
    backgrounds: {
      default: 'dos',
      values: [
        { name: 'dos', value: '#020003' },
        { name: 'light', value: '#FFE8A8' },
      ],
    },
    docs: {
      description: {
        component:
          'Visual primitive for AI-drafted prose. Consumers emit `data-provenance="ai-draft"` on `<p>` / `<li>` / `<blockquote>` elements (per-paragraph), or `data-ai-block` on a wrapper element (whole-section marking). Eidotter renders the magenta→white→cyan shimmer gradient on the text glyphs via `background-clip: text`. The diff machinery (`mark-provenance.mjs`) and explicit human-mark workflow live in consumer repos. See `plans/2026-05-02-001-feat-ai-content-provenance-marker-plan.md` (Phase 1) and the DMNC-946 evolution to the gradient visual.',
      },
    },
  },
} satisfies Meta;

