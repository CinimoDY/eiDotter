/**
 * `data-ai-block` wrapper — whole-section marking. The attribute on the
 * wrapper paints every prose descendant (h1-h6, p, li, blockquote, strong,
 * em, code). Used by non-MDX surfaces where stamping individual elements
 * is impractical.
 */
export const BlockModeWrapper: Story = {
  parameters: {
    docs: {
      description: {
        story:
          'Apply `data-ai-block` to any container element (`<article>`, `<main>`, `<section>`) and every prose descendant inside picks up the gradient. Non-prose descendants (buttons, swatches, terminal previews, etc.) stay untouched because the rule only targets text elements explicitly.',
      },
    },
  },
  render: () => (
    <article className="dos-page" style={proseWidth} data-ai-block>
      <h2 className="dos-body" style={{ fontSize: '1.5em', marginBottom: '0.5em' }}>
        A whole-section AI-marked heading
      </h2>
      <p className="dos-body">
        Every prose element inside this article inherits the gradient via the
        `[data-ai-block] :is(h1, h2, …)` selector.
      </p>
      <p className="dos-body">
        Two paragraphs, both lit. The author can opt-out specific descendants
        with `data-ai-skip="true"` — see the next story.
      </p>
    </article>
  ),
};

/**
 * `data-ai-skip="true"` opt-out. Any descendant of a block-mode wrapper
 * tagged with `data-ai-skip="true"` reverts to its inherited colour.
 * Works both inside `data-ai-block` AND alongside bare
 * `data-provenance="ai-draft"` spans.
 */
export const OptOut: Story = {
  parameters: {
    docs: {
      description: {
        story:
          '`data-ai-skip="true"` is the escape hatch. Use it on a child element when an entire region is AI-marked but a specific subtree should stay un-marked — e.g., quoted attribution, verbatim user input, or styled non-prose components inside an article wrapper.',
      },
    },
  },
  render: () => (
    <article className="dos-page" style={proseWidth} data-ai-block>
      <p className="dos-body">
        Normal AI-marked paragraph — gradient applied.
      </p>
      <div data-ai-skip="true">
        <p className="dos-body">
          This paragraph is inside a `data-ai-skip="true"` wrapper. The
          gradient is suppressed; the text renders in the default inherited
          colour.
        </p>
      </div>
      <p className="dos-body">
        Back to AI-marked — the opt-out scope ended at the wrapper.
      </p>
    </article>
  ),
};

/**
 * `data-ai-skip="true"` nested INSIDE a `data-provenance="ai-draft"` paragraph.
 * Regression guard for DMNC-1314: the skip span must revert to readable body
 * text even though its ancestor paragraph paints transparent glyphs. This is
 * exactly where an InlineExpand content span lands when its trigger word sits
 * in an ai-draft paragraph.
 */
export const SkipInsideProvenance: Story = {
  parameters: {
    docs: {
      description: {
        story:
          'A `data-ai-skip="true"` span nested inside an `ai-draft` paragraph reverts to the default body colour, while the surrounding gradient-marked prose keeps its marker. Without the dedicated reset, the nested skip would inherit the ancestor’s transparent text and vanish. Verify in BOTH the dos (dark) and light backgrounds.',
      },
    },
  },
  render: () => (
    <div className="dos-page" style={proseWidth}>
      <p className="dos-body" data-provenance="ai-draft">
        This sentence carries the AI-draft gradient marker, but{' '}
        <span data-ai-skip="true">
          this nested span opts out and must stay readable
        </span>{' '}
        while the marked text resumes after it.
      </p>
    </div>
  ),
};

